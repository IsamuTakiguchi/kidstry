const SMALL = 'ぁぃぅぇぉっゃゅょー';

export const WORDS = raw.map(([emoji, yomi, en, group]) => ({
  emoji,
  yomi,
  en,
  group,
  head: yomi[0],
  tail: [...yomi].reverse().find((c) => !SMALL.includes(c)),
}));

const SEION = 'あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわをん';

/** あたま もじが せいおん の ことば（レベル1むけ） */
export const SIMPLE_WORDS = WORDS.filter((w) => SEION.includes(w.head));

export const GROUPS = [...new Set(WORDS.map((w) => w.group))];

export function wordsByGroup(group) {
  return WORDS.filter((w) => w.group === group);
}

